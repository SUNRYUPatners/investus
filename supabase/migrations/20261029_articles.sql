-- ────────────────────────────────────────────────────────────────────────────
-- OPTIONAL migration — scalable, bilingual article storage.
--
-- Today the article system (lib/articles.ts) reads from the editorial seeds in
-- lib/reports.ts (the working fallback), so NOTHING breaks without this table.
-- This migration lets daily posts be added without redeploying the ~6.6MB
-- reports.ts bundle: insert rows here and wire getArticlesFromDb() in
-- lib/articles.ts to merge DB rows with the seed fallback.
--
-- Apply this manually in the Supabase dashboard / CLI when you are ready to move
-- storage to the database. It is safe to apply early (the app ignores an empty
-- table).
-- ────────────────────────────────────────────────────────────────────────────

create table if not exists public.articles (
  id            bigint generated by default as identity primary key,
  slug          text not null unique,
  -- Primary ticker / subject for grouping (e.g. TSLA, SPCX). NULL for market-wide.
  ticker        text,
  tickers       text[] not null default '{}',
  category      text not null,
  category_color text not null default 'mint',
  -- Editorial date (publish date), used for sitemap lastmod and ordering.
  published_at  date not null,
  display_date  text,
  images        text[] not null default '{}',
  images_en     text[] not null default '{}',
  -- Korean (source) content.
  title_ko      text not null,
  summary_ko    text not null,
  body_ko        text not null,
  -- English content (site default language). May be NULL until translated.
  title_en      text,
  summary_en    text,
  body_en        text,
  -- Source citations (E-E-A-T): [{ "label": "...", "url": "..." }, ...].
  sources       jsonb not null default '[]'::jsonb,
  -- Set false to hide a post from the public index (e.g. flagged/legacy content).
  is_published  boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create index if not exists articles_published_at_idx on public.articles (published_at desc);
create index if not exists articles_ticker_idx on public.articles (ticker);

-- Row Level Security: public read for published rows; writes via service role only.
alter table public.articles enable row level security;

drop policy if exists "articles public read" on public.articles;
create policy "articles public read"
  on public.articles for select
  using (is_published = true);

-- (No insert/update/delete policy → only the service-role key can write.)
