function extractJsonString(c, keyIdx) {
  const q1 = c.indexOf('"', keyIdx);
  let i = q1 + 1;
  let raw = "";
  while (i < c.length) {
    const ch = c[i];
    if (ch === "\\") {
      raw += ch + c[i + 1];
      i += 2;
      continue;
    }
    if (ch === '"') break;
    raw += ch;
    i++;
  }
  return { decoded: JSON.parse(`"${raw}"`), start: keyIdx, end: i + 1, q1 };
}

