function applyExtra(body, extra, isSummary) {
  const parts = dropCrossDupes(splitSections(body));
  const add = (key, text) => {
    if (!text || !parts[key]) return;
    if (parts[key].includes(text.slice(0, 40))) return;
    parts[key] = `${parts[key]}\n\n${text}`;
  };
  if (isSummary) {
    add("투자 시사점", extra.invest);
    add("오늘의 큰 그림", extra.big);
    add("투자 시사점", extra.note);
  } else {
    add("무슨 일인가요", extra.what);
    add("조금만 더 알려드리면", extra.more);
    add("장기적으로 보면", extra.long);
    add("투자 시사점", extra.invest);
    add("투자 시사점", extra.note);
  }
  return joinSections(parts, isSummary);
}

function processFile(rel) {
  const file = path.join(ROOT, rel);
  const src = fs.readFileSync(file, "utf8");
  const marker = '\n  {\n    id: "';
  const parts = src.split(marker);
  let n = 0;
  const blocks = parts.slice(1).map((chunk) => {
    let block = marker + chunk;
    const id = chunk.match(/^([^"]+)"/)?.[1];
    const extra = id && E[id];
    if (!extra) return block;
    const subject = extractQuoted(block, "subject:").value;
    const pinned = /isPinned:\s*true/.test(block);
    const isSummary = pinned || subject === "한장요약";
    const bodyFound = extractQuoted(block, "body:");
    if (bodyFound.open >= 0) {
      const next = applyExtra(bodyFound.value, extra, isSummary);
      if (next !== bodyFound.value) {
        block = replaceQuoted(block, "body:", next);
        n++;
      }
    }
    if (extra.summary) {
      const s = extractQuoted(block, "summary:");
      if (s.open >= 0 && s.value.length < extra.summary.length) {
        block = replaceQuoted(block, "summary:", extra.summary);
        n++;
      }
    }
    return block;
  });
  const next = parts[0] + blocks.join("");
  if (next !== src) fs.writeFileSync(file, next);
  console.log(`${rel}: ${n} updates`);
}

for (const f of ["lib/reports.ts", "lib/reports-kr.ts", "lib/reports-safe.ts", "lib/reports-kr-re.ts"]) {
  processFile(f);
}
