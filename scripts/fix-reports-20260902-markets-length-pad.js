function serializeData(data) {
  return `/** 2026-09-02 KR / Safe / KR-RE report Korean content */\nmodule.exports = ${JSON.stringify(data, null, 2).replace(/"([^"]+)":/g, "$1:")};\n`;
}

function applyPad(r) {
  const pad = PAD[r.id];
  if (!pad) return;
  if (pad.summaryExtra && r.summary && !r.summary.includes(pad.summaryExtra.trim())) {
    r.summary = `${r.summary.trim()}${pad.summaryExtra}`;
  }
  if (pad.detailExtra && r.detail && !r.detail.includes(pad.detailExtra)) {
    r.detail = `${r.detail.trim()}\n\n${pad.detailExtra}`;
  }
  if (pad.summaryBodyExtra && r.summaryBody && !r.summaryBody.includes(pad.summaryBodyExtra)) {
    r.summaryBody = `${r.summaryBody.trim()}\n\n${pad.summaryBodyExtra}`;
  }
  if (pad.investExtra && r.invest && !r.invest.includes(pad.investExtra)) {
    r.invest = `${r.invest.trim()}\n\n${pad.investExtra}`;
  }
  if (pad.longTermExtra && r.longTerm && !r.longTerm.includes(pad.longTermExtra)) {
    r.longTerm = `${r.longTerm.trim()}\n\n${pad.longTermExtra}`;
  }
  if (pad.forwardExtra && r.forward && !r.forward.includes(pad.forwardExtra)) {
    r.forward = `${r.forward.trim()}\n\n${pad.forwardExtra}`;
  }
}

