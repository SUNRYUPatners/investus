function replacePost(id, alias, symbol, content, likes, created) {
  const re = new RegExp(
    `\\{ id: ${id}, alias: "[^"]*", symbol: "[^"]*", content: "(?:\\\\.|[^"\\\\])*", likes: \\d+, comments: 2, created_at: "[^"]*", liked: false, \\},`,
  );
  const next = `{ id: ${id}, alias: ${esc(alias)}, symbol: ${esc(symbol)}, content: ${esc(content)}, likes: ${likes}, comments: 2, created_at: ${esc(created)}, liked: false, },`;
  if (!re.test(src)) throw new Error(`post ${id} not found`);
  src = src.replace(re, next);
}

function replaceComments(map, baseHour) {
  for (const [id, pairs] of Object.entries(map)) {
    const nid = Number(id);
    const blockRe = new RegExp(
      `\\[${nid}\\]: \\[[\\s\\S]*?\\n  \\],`,
    );
    const t1 = `2026-09-07T${String(baseHour).padStart(2, "0")}:10:00.000Z`;
    const t2 = `2026-09-07T${String(baseHour).padStart(2, "0")}:17:00.000Z`;
    const next = `[${nid}]: [
    { alias: ${esc(pairs[0][0])}, content: ${esc(pairs[0][1])}, created_at: ${esc(t1)} },
    { alias: ${esc(pairs[1][0])}, content: ${esc(pairs[1][1])}, created_at: ${esc(t2)} },
  ],`;
    if (!blockRe.test(src)) throw new Error(`comments ${nid} not found`);
    src = src.replace(blockRe, next);
  }
}

