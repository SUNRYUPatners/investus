const { detailBody, summaryBody } = require("./lib-report-bodies");

function d(label, what, more, longTerm, invest) {
  const whatX = what.concat([
    `${label} 숫자는 오늘 표에만 유효합니다. 집계 시각이 바뀌면 같은 지표라도 칸을 나누시기 바랍니다. 속보 한 줄과 확정 집계를 같은 가중치로 두지 마시기 바랍니다.`,
  ]);
  const moreX = more.concat([
    `${label} 칸에서는 종가·수급·공시의 정의를 먼저 고정하시기 바랍니다. 후속 종가가 나오기 전에는 모델에 넣는 값을 보수적으로 두시기 바랍니다. 단위가 바뀌면 표를 새로 만드시기 바랍니다. 공개 범위와 확정 공시를 같은 가중치로 두지 마시기 바랍니다. 출처 이름보다 숫자 정의가 먼저입니다.`,
    `어제 칸과 오늘 칸을 덮어쓰지 마시기 바랍니다. ${label} 후속 일정이 비어 있으면 가정 가중치를 낮추시기 바랍니다.`,
  ]);
  const longX = longTerm.concat([
    `시간이 지나면 ${label} 축도 반복 측정되는 지표가 쌓입니다. 그때 가정의 가중치를 올리시면 됩니다. 지금은 스냅샷을 칸에 남기는 단계입니다. 한 번의 등락으로 중기 결론을 내지 마시기 바랍니다.`,
  ]);
  const invX = invest.concat([
    `${label} 이슈는 해당 표에서만 추적하시기 바랍니다. 다른 시장 헤드라인과 섞어 한 방향 베팅을 만들지 마시기 바랍니다. 빈칸 지표가 채워지기 전에는 확정 결론을 미루시기 바랍니다.`,
  ]);
  return detailBody({
    what: whatX.join("\n\n"),
    more: moreX.join("\n\n"),
    longTerm: longX.join("\n\n"),
    invest: invX.join("\n\n"),
  });
}

function row(x) {
  const base = {
    id: x.id, slug: x.slug, category: x.category || "종목분석", color: x.color || "mint",
    subject: x.subject, title: x.title, titleEn: x.titleEn, summary: x.summary, summaryEn: x.summaryEn,
  };
  if (x.pinned) {
    return { ...base, type: "summary", isPinned: true, body: x.body };
  }
  return { ...base, body: d(x.subject, x.what, x.more, x.longTerm, x.invest) };
}

