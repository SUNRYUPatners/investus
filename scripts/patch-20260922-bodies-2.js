function extractJsonString(c, keyIdx) {
  const q1 = c.indexOf('"', keyIdx);
  let i = q1 + 1;
  let raw = "";
  while (i < c.length) {
    if (c[i] === "\\") {
      raw += c[i] + c[i + 1];
      i += 2;
      continue;
    }
    if (c[i] === '"') break;
    raw += c[i];
    i++;
  }
  return { decoded: JSON.parse(`"${raw}"`), end: i + 1 };
}

function patchFile(rel) {
  let c = fs.readFileSync(path.join(ROOT, rel), "utf8");
  let n = 0;
  for (const [id, extra] of Object.entries(EXTRA)) {
    const token = `id: "${id}"`;
    const idx = c.indexOf(token);
    if (idx === -1) continue;
    const bodyKey = c.indexOf("\n    body: ", idx);
    if (bodyKey === -1 || bodyKey > idx + 20000) continue;
    const { decoded, end } = extractJsonString(c, bodyKey + "\n    body: ".length);
    if (decoded.includes(MARK2) && decoded.length >= 1000) continue;
    if (decoded.includes(extra)) continue;
    const next = decoded.includes(BK)
      ? decoded.replace(BK, `${extra}\n\n${BK}`)
      : `${decoded}\n\n${extra}`;
    if (c.slice(bodyKey, bodyKey + 20).includes("body: \n")) {
      throw new Error("double body still present " + id);
    }
    c = c.slice(0, bodyKey) + "\n    body: " + JSON.stringify(next) + c.slice(end);
    n++;
    console.log(`  ${id} ${decoded.length} → ${next.length}`);
  }
  fs.writeFileSync(path.join(ROOT, rel), c);
  console.log(rel, n);
}

